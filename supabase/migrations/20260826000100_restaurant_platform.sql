create table if not exists public.store_members (
  store_id uuid not null references public.stores(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','kitchen')),
  created_at timestamptz not null default now(), primary key (store_id,user_id)
);
create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
  name text not null, description text, display_order integer not null default 0, is_active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
  category_id uuid references public.categories(id) on delete set null, name text not null, description text, price numeric(12,2) not null check(price>=0),
  image_url text, tag text, is_available boolean not null default true, options jsonb not null default '[]'::jsonb, created_at timestamptz not null default now()
);
create table if not exists public.offers (
  id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
  title text not null, discount_percentage numeric(5,2) not null default 0 check(discount_percentage between 0 and 100), image_url text, active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.banners (
  id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
  title text not null, subtitle text, image_url text not null, display_order integer not null default 0, active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.addons (
  id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
  title text not null, price numeric(12,2) not null default 0 check(price>=0), image_url text, is_active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(), order_number bigint generated by default as identity,
  store_id uuid not null references public.stores(id) on delete restrict, customer_name text not null, customer_phone text not null,
  order_type text not null check(order_type in ('pickup','delivery')), delivery_address text, notes text, payment_method text not null default 'cash',
  subtotal_amount numeric(12,2) not null default 0, tax_amount numeric(12,2) not null default 0, total_amount numeric(12,2) not null,
  status text not null default 'pending' check(status in ('pending','preparing','ready','completed','cancelled')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(), order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null, product_name text not null, unit_price numeric(12,2) not null,
  quantity integer not null check(quantity between 1 and 100), selected_options jsonb not null default '[]'::jsonb
);
create index if not exists orders_store_status_created_idx on public.orders(store_id,status,created_at);
create index if not exists products_store_category_idx on public.products(store_id,category_id);

create or replace function public.is_store_member(target_store uuid, allowed_roles text[] default array['admin','kitchen'])
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.store_members m where m.store_id=target_store and m.user_id=auth.uid() and m.role=any(allowed_roles));
$$;

