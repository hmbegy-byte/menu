create table if not exists public.stores (
  id uuid primary key default gen_random_uuid(), slug text not null unique, name text not null,
  bio text, phone_whatsapp text not null, currency text not null default 'SAR', is_active boolean not null default true,
  logo_url text, cover_url text, timezone text not null default 'Asia/Riyadh', social_links jsonb not null default '{}'::jsonb, working_hours jsonb not null default '[]'::jsonb,
  appearance jsonb not null default '{}'::jsonb, settings jsonb not null default '{"acceptingOrders":true,"taxPercent":0,"minOrderValue":0}'::jsonb,
  payment jsonb not null default '{"currency":"SAR","cashOnDelivery":true}'::jsonb,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
